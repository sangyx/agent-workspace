import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, expect, it, vi } from 'vitest';
import { AcpAdapter } from '../../src/main/providers/acp';
import { acpAgent } from '../../src/shared/acp-agents';
import type { ProviderSession } from '../../src/main/providers/types';
const opened: ProviderSession[] = [];
afterEach(async () => { for (const session of opened.splice(0)) await session.close(); vi.unstubAllEnvs(); });
it('retains Antigravity reasoning choices, applies them before a prompt, restores the default, and rejects unsupported choices', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'amw-acp-reasoning-')), log = join(dir, 'requests.jsonl');
  vi.stubEnv('FAKE_ACP_DIR', join(dir, 'sessions')); vi.stubEnv('FAKE_ACP_LOG', log); vi.stubEnv('FAKE_ACP_REASONING', '1');
  const adapter = new AcpAdapter(acpAgent('antigravity')!, { command: [process.execPath, join(__dirname, '../fixtures/fake-acp-agent.mjs')] });
  const session = adapter.createSession({ cwd: dir, title: 'Reasoning fixture', permissionMode: 'ask', reasoningEffort: 'high' }, () => {}); opened.push(session);
  await session.start();
  const models = await adapter.listModels(); expect(models.length).toBeGreaterThan(0);
  expect(models[0].reasoningEfforts).toEqual(['low', 'medium', 'high']);
  const requests = () => readFileSync(log, 'utf8').trim().split('\n').map(line => JSON.parse(line));
  expect(requests().some(r => r.method === 'session/prompt')).toBe(false);
  await session.setReasoningEffort!('high');
  expect(requests().some(r => r.method === 'session/set_config_option' && r.params.configId === 'thought_level' && r.params.value === 'high')).toBe(true);
  await expect(session.setReasoningEffort!('unsupported')).rejects.toThrow('does not offer reasoning effort');
  await session.setReasoningEffort!(null);
  expect(requests().filter(r => r.method === 'session/set_config_option' && r.params.configId === 'thought_level').at(-1)?.params.value).toBe('medium');
  await session.setReasoningEffort!('low');
  await session.send('Respond briefly.');
  const calls = requests(); const set = calls.findLastIndex(r => r.method === 'session/set_config_option' && r.params.value === 'low');
  await vi.waitFor(() => expect(requests().some(r => r.method === 'session/prompt')).toBe(true));
  expect(set).toBeLessThan(requests().findIndex(r => r.method === 'session/prompt'));
});
